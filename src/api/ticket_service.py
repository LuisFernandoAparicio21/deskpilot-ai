"""``crear_ticket``: redact, classify, set the SLA and store a new ticket (S9, RF-16, RN-01..05).

Order of decisions:

1. Redact sensitive data (RN-05, RF-10) *before* anything else: classification, the LLM,
   the database and the logs only ever see the redacted text. The redacted text is cut to
   ``api.max_description_chars`` (placeholders can be longer than the secret they replace).
2. Classify (``classification``): RN-03 cases are P1 and flagged ``escalado``.
3. SLA hours from ``config.yaml`` (RN-02) for the final priority.
4. Persist through ``TicketRepository.create_ticket`` (id generated by the server).

Logs carry only the ticket id, category, priority and flags; never the description.
"""

from __future__ import annotations

import logging
from collections.abc import Callable
from datetime import UTC, datetime, timedelta
from typing import Protocol

from src.api.classification import classify
from src.api.repository import NewTicket, TicketRepository
from src.api.schemas import CrearTicketRequest, CrearTicketResponse
from src.llm import LLMClient
from src.retrieval.language import detect_language
from src.utils.config import Settings
from src.utils.redaction import contains_sensitive, redact

logger = logging.getLogger(__name__)


class TicketCreator(Protocol):
    """What ``crear_ticket`` needs; ``TicketService`` implements it (REST and MCP share it)."""

    def create(self, request: CrearTicketRequest) -> CrearTicketResponse: ...


def _utc_now() -> datetime:
    """Naive UTC now without microseconds (the dataset stores naive seconds)."""
    return datetime.now(UTC).replace(tzinfo=None, microsecond=0)


class TicketService:
    """Creates tickets; raises ``RepositoryUnavailableError`` when they cannot be stored."""

    def __init__(
        self,
        repository: TicketRepository,
        llm: LLMClient,
        settings: Settings,
        clock: Callable[[], datetime] = _utc_now,
    ) -> None:
        self._repository = repository
        self._llm = llm
        self._timeout_s = settings.llm.timeout_s
        self._max_chars = settings.api.max_description_chars
        self._sla = settings.sla_horas.model_dump()
        self._clock = clock

    def create(self, request: CrearTicketRequest) -> CrearTicketResponse:
        kinds = contains_sensitive(request.descripcion)
        text = redact(request.descripcion)[: self._max_chars] if kinds else request.descripcion
        classification = classify(text, self._llm, self._timeout_s)
        sla_hours = int(self._sla[classification.prioridad])
        opened = self._clock()
        ticket_id = self._repository.create_ticket(
            NewTicket(
                fecha_apertura=opened,
                categoria=classification.categoria,
                subcategoria=classification.subcategoria,
                prioridad=classification.prioridad,
                sucursal=request.sucursal,
                area=request.area,
                canal=request.canal,
                sla_horas=sla_hours,
                idioma=detect_language(text),
                descripcion=text,
            )
        )
        logger.info(
            "Ticket created",
            extra={
                "ticket_id": ticket_id,
                "categoria": classification.categoria,
                "prioridad": classification.prioridad,
                "escalado": classification.escalated,
                "mode": classification.mode,
                "sensitive_kinds": len(kinds),
            },
        )
        return CrearTicketResponse(
            ticket_id=ticket_id,
            estado="abierto",
            categoria=classification.categoria,
            subcategoria=classification.subcategoria,
            prioridad=classification.prioridad,
            sla_horas=sla_hours,
            fecha_apertura=opened,
            fecha_limite_sla=opened + timedelta(hours=sla_hours),
            escalado=classification.escalated,
            motivo_escalamiento=classification.escalation,
            sensitive_data_warning=bool(kinds),
            mode=classification.mode,
        )
